#!/usr/bin/env python3
"""
build.py — one command to go from a script to a finished vertical video.

    python kit/build.py --film films/my-film/film.json

Steps (skip any with --steps):
    voice    narration + timings + lip-sync envelope      (kit/voice.py)
    music    procedural score stem                        (kit/music.py)
    mix      ducking, loudness target, stems, report      (kit/mix.py)
    site     assemble build/<slug>/site and generate timeline.js
    render   headless frames, resumable, chunked          (kit/render.js)
    encode   frames + mix.wav -> mp4                      (kit/encode.py)
    qa       frame + loudness checks on the result        (kit/qa.py)

Rendering is slow on CPU-only machines (~2-5 s per 1080x1920 frame), so it runs
in chunks and resumes: kill it, run it again, it continues where it stopped.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIT = os.path.join(ROOT, "kit")
LIB = os.path.join(KIT, "lib")
NODE = os.environ.get("NODE", "node")
QUERY = ""


def run(cmd, **kw):
    print("   $", " ".join(str(c) for c in cmd))
    return subprocess.run(cmd, **kw)


# --------------------------------------------------------------------------- #
def step_voice(film_path, build, force):
    out = os.path.join(build, "timings.json")
    if os.path.exists(out) and not force:
        # a stale cache is the single most confusing failure in this pipeline:
        # the script changed, the timings did not, and beats point at lines that
        # no longer exist. Re-synthesise whenever the line ids differ.
        film = json.load(open(film_path, encoding="utf-8"))
        cached = json.load(open(out)).get("lines", {})
        want = [l["id"] for l in film.get("lines", [])]
        if list(cached.keys()) == want:
            print("  voice: cached (use --force to re-synthesise)")
            return
        print("  voice: script changed — re-synthesising")
    run([sys.executable, os.path.join(KIT, "voice.py"), "--film", film_path, "--out", build], check=True)


def step_music(film_path, build):
    run([sys.executable, os.path.join(KIT, "music.py"), "--film", film_path, "--build", build], check=True)


def step_mix(build, film):
    audio = film.get("audio", {})
    run([sys.executable, os.path.join(KIT, "mix.py"), "--build", build,
         "--target", str(audio.get("target_lufs", -14.0)),
         "--ceiling", str(audio.get("ceiling_dbtp", -1.5)),
         "--duck", str(audio.get("duck_db", -3.5))], check=True)


def step_site(film_path, build, film):
    for need in ("timings.json", "envelope.json"):
        if not os.path.exists(os.path.join(build, need)):
            raise SystemExit(
                f"missing {need} in {build} — the site step needs the voice step first.\n"
                f"Run:  python kit/build.py --film {film_path} --steps voice,music,mix,site")
    site = os.path.join(build, "site")
    os.makedirs(site, exist_ok=True)

    # scene code ships with the film; everything else comes from the kit
    film_dir = os.path.dirname(os.path.abspath(film_path))
    shutil.copy2(os.path.join(film_dir, "scene.js"), os.path.join(site, "scene.js"))
    shutil.copy2(os.path.join(ROOT, "templates", "index.html"), os.path.join(site, "index.html"))
    shutil.copy2(os.path.join(build, "envelope.json"), os.path.join(site, "envelope.json"))

    for item in ("three.module.js", "jsm", "fonts", "assets"):
        src, dst = os.path.join(LIB, item), os.path.join(site, item)
        if os.path.isdir(src):
            shutil.copytree(src, dst, dirs_exist_ok=True)
        elif os.path.exists(src):
            shutil.copy2(src, dst)

    # ---- generated timeline: every cut is derived from measured audio ----
    timings = json.load(open(os.path.join(build, "timings.json")))
    beats = film.get("beats", {})
    T = {"s1": 0.0}
    for key, line_id in beats.items():
        if line_id not in timings["lines"]:
            raise SystemExit(f"beat {key!r} points at unknown line {line_id!r}")
        T[key] = timings["lines"][line_id]["start"]
    T["end"] = timings["total"]

    with open(os.path.join(site, "timeline.js"), "w") as fh:
        fh.write("// generated by kit/build.py — do not edit\n")
        fh.write(f"export const FPS = {film.get('fps', 24)};\n")
        fh.write(f"export const DUR = {timings['total']};\n")
        fh.write(f"export const T = {json.dumps(T, indent=1)};\n")
        fh.write(f"export const LINES = {json.dumps(timings['lines'], indent=1)};\n")

    with open(os.path.join(site, "film.js"), "w") as fh:
        fh.write("// generated by kit/build.py — edit film.json instead\n")
        fh.write("export const FILM = " + json.dumps(film, ensure_ascii=False, indent=1) + ";\n")

    frames = round(timings["total"] * film.get("fps", 24))
    print(f"  site: {site}  ({frames} frames, {timings['total']:.2f}s)")


def step_render(build, film, chunk_seconds=280, workers=1):
    """Render every frame. Resumable: a kill, a crash or a timeout just resumes."""
    site = os.path.join(build, "site")
    frames = os.path.join(build, "frames")
    os.makedirs(frames, exist_ok=True)
    timings = json.load(open(os.path.join(build, "timings.json")))
    total = int(round(timings["total"] * film["fps"]))
    t0 = time.time()

    def have():
        return len([f for f in os.listdir(frames) if f.endswith(".jpg")])

    if workers <= 1:
        while have() < total:
            if time.time() - t0 > 6 * 3600:
                raise SystemExit("render exceeded 6 hours; check the log")
            before = have()
            run([NODE, os.path.join(KIT, "render.js"), "--site", site, "--out", frames,
                 "--from", "0", "--to", str(total - 1), "--resume", "--port", "8731",
                 "--query", QUERY], check=False, timeout=chunk_seconds)
            print(f"  render: {have()}/{total} frames")
            if have() == before:
                raise SystemExit("no progress — the scene is failing; run render.js --list=0 to see the error")
        return

    # parallel: split the frame range into contiguous slices, one browser each
    print(f"  render: {workers} workers, {total} frames")
    while have() < total:
        if time.time() - t0 > 6 * 3600:
            raise SystemExit("render exceeded 6 hours; check the log")
        before = have()
        per = (total + workers - 1) // workers
        procs = []
        for w in range(workers):
            a = w * per
            b = min(total - 1, a + per - 1)
            if a >= total:
                break
            procs.append(subprocess.Popen(
                [NODE, os.path.join(KIT, "render.js"), "--site", site, "--out", frames,
                 "--from", str(a), "--to", str(b), "--resume", "--port", str(8731 + w),
                 "--query", QUERY],
                cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL))
        deadline = time.time() + chunk_seconds
        for pr in procs:
            left = max(1, int(deadline - time.time()))
            try:
                pr.wait(timeout=left)
            except subprocess.TimeoutExpired:
                pr.kill()
        print(f"  render: {have()}/{total} frames")
        if have() == before:
            raise SystemExit("no progress — the scene is failing; run render.js --list=0 to see the error")


def step_encode(build, film, out_path):
    run([sys.executable, os.path.join(KIT, "encode.py"),
         "--frames", os.path.join(build, "frames"),
         "--audio", os.path.join(build, "mix.wav"),
         "--fps", str(film.get("fps", 24)),
         "--out", out_path], check=True)


# --------------------------------------------------------------------------- #
def main() -> int:
    global QUERY
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--film", required=True, help="path to film.json")
    ap.add_argument("--build", help="build directory (default build/<slug>)")
    ap.add_argument("--steps", default="voice,music,mix,site,render,encode,qa")
    ap.add_argument("--force", action="store_true", help="re-synthesise the voice")
    ap.add_argument("--chunk-seconds", type=int, default=280)
    ap.add_argument("--workers", type=int, default=1,
                    help="render N slices in parallel (use your core count; ~1 worker per 2 cores is fastest)")
    ap.add_argument("--port", type=int, default=8500)
    ap.add_argument("--query", default="", help="extra page query, e.g. w=540&h=960 for quick tests")
    ap.add_argument("--qa-ignore", default="", help="checks QA should tolerate, e.g. pops")
    args = ap.parse_args()
    QUERY = args.query

    film = json.load(open(args.film, encoding="utf-8"))
    slug = film.get("slug") or os.path.splitext(os.path.basename(args.film))[0]
    build = os.path.abspath(args.build or os.path.join(ROOT, "build", slug))
    os.makedirs(build, exist_ok=True)
    steps = [s.strip() for s in args.steps.split(",") if s.strip()]

    print(f"film: {film.get('title', slug)}  ->  {build}")
    if "voice" in steps:
        step_voice(args.film, build, args.force)
    if "music" in steps:
        step_music(args.film, build)
    if "mix" in steps:
        step_mix(build, film)
    if "site" in steps:
        step_site(args.film, build, film)
    if "render" in steps:
        step_render(build, film, args.chunk_seconds, args.workers)
    if "encode" in steps:
        step_encode(build, film, os.path.join(build, f"{slug}.mp4"))
    if "qa" in steps and os.path.exists(os.path.join(build, f"{slug}.mp4")):
        run([sys.executable, os.path.join(KIT, "qa.py"),
             "--video", os.path.join(build, f"{slug}.mp4"),
             "--out", os.path.join(build, "qa"), "--frames", os.path.join(build, "qa"),
             "--ignore", args.qa_ignore], check=False)

    print("done.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
